def _checked_scale(scale: int) -> int:
    """`scale` if it is a whole number of 1 or more."""
    if not isinstance(scale, int) or isinstance(scale, bool) or scale < 1:
        raise PixelRowsError(f"scale must be a whole number of 1 or more, got {scale!r}")
    return scale


def text_width(text: str, scale: int = 1) -> int:
    """
    How wide `text` is drawn, in pixels.

    Glyphs sit 6 apart, times `scale`, and nothing is counted after the last one.
    """
    if not isinstance(text, str):
        raise PixelRowsError(f"text must be a string, got {type(text).__name__}")
    _checked_scale(scale)
    if not text:
        return 0
    return (len(text) * _ADVANCE - 1) * scale


def draw_text(image: Image, text: str, x: int, y: int, colour: str | RGB = "#ffffff", scale: int = 1) -> int:
    """
    Draws `text` on `image` with its top-left corner at (x, y) and returns the x just past the last glyph.

    Each pixel of ink becomes a `scale` by `scale` block of `colour`, and the
    rest is left as it is. A lower-case letter is drawn as its capital, and
    any other character without a glyph as a blank. What falls outside the
    image is dropped.
    """
    end = x + text_width(text, scale)
    rgb = as_rgb(colour)
    for i, ch in enumerate(text):
        glyph = FONT.get(ch.upper())
        if glyph is None:
            continue
        left = x + i * _ADVANCE * scale
        for row, line in enumerate(glyph):
            for column, cell in enumerate(line):
                if cell == "#":
                    image.fill(left + column * scale, y + row * scale, scale, scale, rgb)
    return end
